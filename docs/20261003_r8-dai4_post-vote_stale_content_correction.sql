do $$
declare
  v_expected_content integer;
  v_expected_summary integer;
  v_updated_content integer;
  v_updated_summary integer;
  v_not_corrected integer;
  v_forbidden integer;
  v_missing_result integer;
  v_outside_target integer;
  v_title_changed integer;
begin
  select expected_content_updates, expected_summary_updates into v_expected_content, v_expected_summary from _r8fix_run_metrics;
  select count(*) into v_updated_content from _r8fix_updated_content_ids;
  select count(*) into v_updated_summary from _r8fix_updated_summary_ids;
  if v_updated_content <> v_expected_content or v_updated_summary <> v_expected_summary then
    raise exception 'Expected % content / % summary updates, updated % / %',
      v_expected_content, v_expected_summary, v_updated_content, v_updated_summary;
  end if;

  -- 全22行が修正後の本文になっていること
  select count(*) into v_not_corrected
  from _r8fix_edits e
  join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level
  where bc.content is distinct from e.new_content
     or (e.new_summary is not null and bc.summary is distinct from e.new_summary);
  if v_not_corrected <> 0 then raise exception 'Post-update verification failed for % rows', v_not_corrected; end if;

  -- 採決前・内部作業状況の文言が残っていないこと
  select count(*) into v_forbidden
  from _r8fix_edits e
  join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level
  where (bc.content || E'\n' || bc.summary) ~ '6月24日予定|採決予定|現時点では未確定|まだ何も決まっ|審査が続|委員会文字起こし待ち|記録が得られ次第|審査記録は未取得|文字起こしが未取得|委員会での審査の内容|見出しのみ取得|見出しレベルで確認|取得範囲に無い|結論（採決）は6月24日|審議されます|審議が行われます|必要性が議会で確認されます|文字起こしを確認できていない|本文は未取得|ASR';
  if v_forbidden <> 0 then raise exception 'Stale phrases remain in % rows', v_forbidden; end if;

  -- 「採決の結果」が各行にちょうど1つあること
  select count(*) into v_missing_result
  from _r8fix_edits e
  join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level
  where (length(bc.content) - length(replace(bc.content, E'## 採決の結果\n', ''))) / length(E'## 採決の結果\n') <> 1;
  if v_missing_result <> 0 then raise exception 'Result section is not exactly once in % rows', v_missing_result; end if;

  -- 対象外の行（対象会期の他の議案・対象議案の他の列）が変わっていないこと
  select count(*) into v_outside_target
  from _r8fix_rows_before before_row
  join bill_contents bc on bc.id = before_row.id
  where (before_row.content_md5 is distinct from md5(bc.content) or before_row.summary_md5 is distinct from md5(bc.summary))
    and not exists (select 1 from _r8fix_edits e where e.bill_id = before_row.bill_id and e.difficulty_level = before_row.difficulty_level);
  if v_outside_target <> 0 then raise exception 'Non-target rows changed: %', v_outside_target; end if;

  select count(*) into v_title_changed
  from _r8fix_rows_before before_row
  join bill_contents bc on bc.id = before_row.id
  where bc.title is distinct from before_row.title
     or bc.bill_id is distinct from before_row.bill_id
     or bc.difficulty_level is distinct from before_row.difficulty_level;
  if v_title_changed <> 0 then raise exception 'title / mapping changed in % rows', v_title_changed; end if;
end $$;

