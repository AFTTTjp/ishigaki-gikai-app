- 遠隔地加算：市外に居住する委員が委員会等に出席する場合に限り、移動に伴う時間的拘束や本業における機会損失を評価する観点から、往復の移動時間が2時間未満の場合は2万円、2時間以上の場合は4万円を加算。
- 目的：中立かつ高度な知見を有する外部専門家の確実な確保。

