declare
  v_bad_bill_count integer;
  v_edit_rows integer;
  v_drift_rows integer;
  v_session_id uuid;
begin
  select id into v_session_id from diet_sessions where slug = 'ishigaki-r8-dai4-teireikai';
  if v_session_id is null then raise exception 'diet_session ishigaki-r8-dai4-teireikai not found'; end if;

  select count(*) into v_bad_bill_count
  from _r8fix_target_bills t
  left join bills b on b.id = t.bill_id
  where b.id is null
     or b.name is distinct from t.official_bill_name
     or b.diet_session_id is distinct from v_session_id
     or b.document_type is distinct from 'bill';
  if v_bad_bill_count <> 0 then
    raise exception 'Preflight failed: % target bills do not match (id / name / session / document_type)', v_bad_bill_count;
  end if;

  select count(*) into v_edit_rows
  from _r8fix_edits e
  join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level;
  if v_edit_rows <> 22 then
    raise exception 'Preflight failed: expected 22 target bill_contents rows, found %', v_edit_rows;
  end if;

  -- 現在の本文が「想定する旧本文」でも「修正後の本文」でもない行（＝想定外の編集が入っている行）があれば中止
  select count(*) into v_drift_rows
  from _r8fix_edits e
  join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level
  where not (md5(bc.content) = e.old_content_md5 or bc.content = e.new_content)
     or (e.new_summary is not null
         and not (md5(bc.summary) = e.old_summary_md5 or bc.summary = e.new_summary));
  if v_drift_rows <> 0 then
    raise exception 'Preflight failed: % rows differ from both the expected old text and the corrected text', v_drift_rows;
  end if;
end $$;

-- 変更前のスナップショット（対象外の行が変わっていないことの検証用。対象会期の全議案が範囲）
create temp table _r8fix_rows_before on commit drop as
select bc.id, bc.bill_id, bc.difficulty_level, bc.title, md5(bc.summary) as summary_md5, md5(bc.content) as content_md5
from bill_contents bc
join bills b on b.id = bc.bill_id
where b.diet_session_id = (select id from diet_sessions where slug = 'ishigaki-r8-dai4-teireikai');

create temp table _r8fix_run_metrics on commit drop as
select
  count(*) filter (where md5(bc.content) = e.old_content_md5) as expected_content_updates,
  count(*) filter (where e.new_summary is not null and md5(bc.summary) = e.old_summary_md5) as expected_summary_updates
from _r8fix_edits e
join bill_contents bc on bc.bill_id = e.bill_id and bc.difficulty_level = e.difficulty_level;

-- 更新（bill_id + difficulty_level + 旧本文の md5 が一致する行だけ。content と summary のみ）
create temp table _r8fix_updated_content_ids (content_id uuid primary key) on commit drop;
create temp table _r8fix_updated_summary_ids (content_id uuid primary key) on commit drop;

with updated as (
  update bill_contents bc
  set content = e.new_content
  from _r8fix_edits e
  where bc.bill_id = e.bill_id
    and bc.difficulty_level = e.difficulty_level
    and md5(bc.content) = e.old_content_md5
  returning bc.id
)
insert into _r8fix_updated_content_ids (content_id) select id from updated;

with updated as (
  update bill_contents bc
  set summary = e.new_summary
  from _r8fix_edits e
  where bc.bill_id = e.bill_id
    and bc.difficulty_level = e.difficulty_level
    and e.new_summary is not null
    and md5(bc.summary) = e.old_summary_md5
  returning bc.id
)
insert into _r8fix_updated_summary_ids (content_id) select id from updated;

